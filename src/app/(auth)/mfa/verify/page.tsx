"use client";
import React, { useState, useEffect } from 'react';
import { useAuth } from '@/context/AuthContext';
import { useRouter } from 'next/navigation';

export default function MfaVerifyPage() {
  const { user, loading } = useAuth();
  const router = useRouter();
  const [code, setCode] = useState('');
  const [error, setError] = useState('');
  const [verifying, setVerifying] = useState(false);

  useEffect(() => {
    if (!loading && !user) {
      router.push('/login');
    }
  }, [user, loading, router]);

  const handleVerify = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!user) return;
    setVerifying(true);
    setError('');

    try {
      const token = await user.getIdToken();
      const res = await fetch('/api/auth/mfa/verify', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${token}` },
        body: JSON.stringify({ code })
      });
      
      if (res.ok) {
        // Force refresh Token so if custom claims (if any exist) update, they are fetched
        await user.getIdToken(true);
        router.push('/dashboard');
      } else {
        const data = await res.json();
        setError(data.error || 'Invalid code. Try again.');
      }
    } catch (err) {
      setError('Verification failed. Network issue.');
    } finally {
      setVerifying(false);
    }
  };

  if (loading) return null;

  return (
    <div className="min-h-screen flex items-center justify-center p-6">
      <div className="glass-card max-w-sm w-full p-10 rounded-3xl shadow-2xl transition-all duration-500">
        <div className="flex flex-col items-center mb-8 text-center">
          <div className="w-16 h-16 rounded-2xl bg-gradient-to-br from-primary to-primary-dim flex items-center justify-center shadow-lg shadow-primary/20 mb-6">
            <span className="material-symbols-outlined text-on-primary text-4xl">lock</span>
          </div>
          <h1 className="font-headline text-2xl font-extrabold tracking-tight text-on-surface">Two-Factor Auth</h1>
          <p className="text-on-surface-variant text-sm mt-2">Enter the PIN generated by your authenticator app.</p>
        </div>

        {error && <div className="mb-6 p-4 bg-error/10 border border-error/20 text-error rounded-xl text-sm font-bold text-center">{error}</div>}

        <form onSubmit={handleVerify} className="space-y-6">
          <div className="space-y-2">
            <input 
              className="w-full bg-surface-container-lowest border-2 border-outline-variant/30 rounded-xl px-4 py-4 text-center text-3xl tracking-[0.4em] font-mono text-primary font-bold placeholder:text-outline-variant/50 focus:outline-none focus:border-primary focus:ring-4 focus:ring-primary/20 transition-all"
              type="text" maxLength={6} placeholder="######"
              value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} autoFocus required
            />
          </div>

          <button 
            type="submit" disabled={verifying || code.length < 6}
            className="w-full py-4 bg-gradient-to-br from-primary to-primary-dim text-on-primary rounded-xl font-bold shadow-xl hover:scale-105 active:scale-95 transition-all disabled:opacity-50 disabled:cursor-not-allowed"
          >
            {verifying ? 'Authenticating...' : 'Confirm Identity'}
          </button>
        </form>
      </div>
    </div>
  );
}
